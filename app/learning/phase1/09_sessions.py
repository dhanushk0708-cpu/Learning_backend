# WHY?
# Sessions store user login information
# on the server.

# HOW IT WORKS

# User Login
#
# ↓
#
# Server creates Session
#
# ↓
#
# Session ID stored in Cookie
#
# ↓
#
# Browser sends Session ID
# with every request

# INTERVIEW

# Q: What is a Session?
#
# A:
# A Session stores user information
# on the server and identifies
# the logged-in user.

# REMEMBER

# ✔ Data stored on Server
# ✔ Browser stores only Session ID
# ✔ Session ID is usually stored in a Cookie
